function timeOfDay(hour) {
  if (hour >= 5 && hour < 12) return 'morning';
  if (hour >= 12 && hour < 17) return 'afternoon';
  if (hour >= 17 && hour < 22) return 'evening';
  return 'night';
}

// Pick a random entry, avoiding whatever was shown last time
function pickFresh(pool, storageKey) {
  const last = localStorage.getItem(storageKey);
  const candidates = pool.length > 1 ? pool.filter(item => item !== last) : pool;
  const choice = candidates[Math.floor(Math.random() * candidates.length)];
  localStorage.setItem(storageKey, choice);
  return choice;
}

export function pickGreeting(name, now = new Date()) {
  const slot = timeOfDay(now.getHours());
  const day = now.getDay();

  const titlePool = [...TITLES[slot], ...TITLES.anytime, ...(TITLES.days[day] || [])];
  const subtitlePool = [...SUBTITLES[slot], ...SUBTITLES.anytime, ...(SUBTITLES.days[day] || [])];

  return {
    title: pickFresh(titlePool, 'greeting_last_title').replaceAll('{name}', name),
    subtitle: pickFresh(subtitlePool, 'greeting_last_subtitle')
  };
}
